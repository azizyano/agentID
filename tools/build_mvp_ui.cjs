// Build the dependency-free MVP UI configuration from the reviewed deployment package.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const {preparePackage} = require('./prepare_mvp_deployment.cjs');
const ethers = require(path.join(root, 'verification', 'wallet-tests', 'node_modules', 'ethers'));

const contractAddress = '0x8ACF294c769e25dAb44aCbEb83fc401cA0702388';
const officialRegistry = '0x60B9262456dE011F7d15a54CdD8c48bAaa8B022F';
const signatures = [
  'agentIdRegistry()',
  'BSC_AGENT_ID_REGISTRY()',
  'BSC_MAINNET_CHAIN_ID()',
  'receiptCount()',
  'uniqueAgentCount()',
  'isAgentIdHolder(address)',
  'hasParticipated(address)',
  'recorded(address,bytes32)',
  'balanceOf(address)',
  'recordAssessment(bytes32,bytes32)',
];

function buildConfig() {
  const prepared = preparePackage();
  const selectors = Object.fromEntries(signatures.map(signature => [signature, ethers.id(signature).slice(0, 10)]));
  const runtime = prepared.linkedRuntimeBytecode.toLowerCase();
  if (ethers.keccak256(runtime) !== prepared.plan.expected_runtime_keccak256) {
    throw new Error('Linked UI runtime differs from the approved deployment plan');
  }
  return {
    schemaVersion: 1,
    chainId: 56,
    chainIdHex: '0x38',
    chainName: 'BNB Smart Chain',
    contractAddress,
    officialRegistry,
    expectedRuntime: runtime,
    expectedRuntimeKeccak256: prepared.plan.expected_runtime_keccak256,
    expectedRuntimeSha256: '0x' + crypto.createHash('sha256').update(Buffer.from(runtime.slice(2), 'hex')).digest('hex'),
    explorerBaseUrl: 'https://bscscan.com',
    targetUniqueAgents: 30,
    evidenceDomain: 'veriabstain.ui.contract-integrity.evidence.v1',
    assessmentDomain: 'veriabstain.ui.contract-integrity.assessment.v1',
    selectors,
  };
}

function writeConfig(output) {
  const destination = path.resolve(output);
  fs.mkdirSync(path.dirname(destination), {recursive: true});
  const body = `// Generated by tools/build_mvp_ui.cjs; do not edit manually.\n` +
    `globalThis.VERIABSTAIN_CONFIG = Object.freeze(${JSON.stringify(buildConfig(), null, 2)});\n`;
  fs.writeFileSync(destination, body, 'utf8');
  return destination;
}

function main(argv) {
  if (argv.length !== 2 || argv[0] !== '--output') throw new Error('Use --output <path>');
  const destination = writeConfig(argv[1]);
  process.stdout.write(JSON.stringify({status: 'MVP_UI_CONFIG_BUILT', output: destination}) + '\n');
}

module.exports = {buildConfig, writeConfig};
if (require.main === module) main(process.argv.slice(2));
